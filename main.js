function switchTab(tabId, btn) {
  document
    .querySelectorAll(".cls-tab-content")
    .forEach((c) => c.classList.remove("act"));
  document
    .querySelectorAll(".cls-tab")
    .forEach((b) => b.classList.remove("act"));
  document.getElementById("tab-" + tabId).classList.add("act");
  // find the right button by tab name
  const allTabs = document.querySelectorAll(".cls-tab");
  allTabs.forEach((b) => {
    if (b.onclick && b.onclick.toString().includes("'" + tabId + "'"))
      b.classList.add("act");
  });
  // fallback: use passed btn
  if (btn) btn.classList.add("act");
}

