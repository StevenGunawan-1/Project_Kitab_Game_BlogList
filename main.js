function applyRecStats(classId) {
  const rec = REC_STATS[classId];
  if (rec) {
    statState[classId] = { ...rec };
  } else {
    const init = { STR: 1, AGI: 1, VIT: 1, INT: 1, DEX: 1, LUK: 1 };
    const C = CLASS_DATA[classId];
    C.dist.forEach((d) => {
      const key = d.stat;
      const val = parseInt(d.pts.toString().split("–")[0]) || 1;
      if (init.hasOwnProperty(key)) init[key] = Math.max(1, Math.min(99, val));
    });
    statState[classId] = init;
  }
  const C = CLASS_DATA[classId];
  renderStatAllocator(classId, C, 1273);
}

