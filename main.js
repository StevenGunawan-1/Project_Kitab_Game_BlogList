function doSearch(v) {
  curS = v.toLowerCase().trim();
  applyF();
  // Scroll ke section posts jika ada query
  if (curS) {
    const postsSection = document.getElementById("posts");
    if (postsSection)
      postsSection.scrollIntoView({ behavior: "smooth", block: "start" });
  }
}
function triggerSearch() {
  const input = document.getElementById("si");
  if (input) doSearch(input.value);
}
function applyF() {
  let vis = 0;
  document.querySelectorAll(".pc").forEach((c) => {
    const cm = curF === "all" || c.dataset.cat === curF;
    const sm = !curS || (c.dataset.title || "").includes(curS);
    const show = cm && sm;
    c.style.display = show ? "flex" : "none";
    if (show) vis++;
  });
  const nores = document.getElementById("nores");
  if (nores) nores.style.display = vis === 0 ? "block" : "none";
}

