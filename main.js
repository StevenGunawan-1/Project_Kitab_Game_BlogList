// Build one family tree (single class)
function buildFamilyHTML(famKey) {
  const T = JOB_TREE[famKey];
  if (!T) return "";
  const NODE_W = 148,
    GAP = 12;
  let h = "";
  // base node
  h += `<div style="display:flex;flex-direction:column;align-items:center">`;
  h += tn(T.base);
  h += tvline(28);

  const bc = T.chains.length;
  if (bc === 1) {
    // single chain – just stack vertically
    T.chains[0].forEach((nd, i) => {
      h += tn(nd);
      if (i < T.chains[0].length - 1) h += tvline(28);
    });
  } else {
    // multi-branch
    const totalW = bc * NODE_W + (bc - 1) * GAP;
    const innerW = totalW - NODE_W; // span between centers
    // horizontal bar
    h += `<div style="position:relative;width:${totalW}px;height:2px;margin:0 auto">`;
    h += `<div style="position:absolute;top:0;left:${NODE_W / 2}px;right:${NODE_W / 2}px;height:2px;background:rgba(201,162,39,.45)"></div>`;
    h += `</div>`;
    // branches
    h += `<div style="display:flex;align-items:flex-start;gap:${GAP}px">`;
    T.chains.forEach((chain) => {
      h += `<div style="display:flex;flex-direction:column;align-items:center;width:${NODE_W}px">`;
      h += tvline(28);
      chain.forEach((nd, i) => {
        h += tn(nd);
        if (i < chain.length - 1) h += tvline(28);
      });
      h += `</div>`;
    });
    h += `</div>`;
  }
  h += `</div>`;
  return h;
}

