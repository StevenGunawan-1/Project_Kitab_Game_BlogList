// skill points store (separate from CLASS_DATA builds)
const skPts = {};
Object.values(SK_DATA).forEach((tiers) =>
  tiers.forEach((t) =>
    t.skills.forEach((s) => {
      if (skPts[s.id] === undefined) skPts[s.id] = 0;
    }),
  ),
);

let _skClass = "knight";

function skGetTierPts(cls, tid) {
  const t = SK_DATA[cls]?.find((t) => t.id === tid);
  return t ? t.skills.reduce((a, s) => a + (skPts[s.id] || 0), 0) : 0;
}
function skIsTierUnlocked(cls, tier) {
  if (!tier.unlockFrom) return true;
  return skGetTierPts(cls, tier.unlockFrom) >= tier.unlock;
}

function skRenderTree(cls) {
  _skClass = cls;
  const tiers = SK_DATA[cls];
  if (!tiers) return;

  // total bar
  const tb = document.getElementById("sk-total-bar");
  if (tb)
    tb.innerHTML = tiers
      .map((t) => {
        const pts = skGetTierPts(cls, t.id);
        const ok = skIsTierUnlocked(cls, t);
        return `<div style="font-size:11px;padding:4px 10px;border:1px solid ${t.border};background:${t.bg};display:flex;align-items:center;gap:5px">
      <span class="sk-badge" style="background:${t.bg};color:${t.color};border:1px solid ${t.border}">${t.badge}</span>
      <span style="font-family:'Share Tech Mono',monospace;font-size:11px;font-weight:700;color:var(--gold)">${pts} pts</span>
      ${!ok ? '<span style="font-size:10px;color:var(--muted)">(terkunci)</span>' : ""}
    </div>`;
      })
      .join("");

  // tiers
  const tc = document.getElementById("sk-tiers");
  if (!tc) return;
  tc.innerHTML = "";
  tiers.forEach((tier) => {
    const unlocked = skIsTierUnlocked(cls, tier);
    const tierPts = skGetTierPts(cls, tier.id);
    const div = document.createElement("div");
    div.className = "sk-tier";

    let lockHTML = "";
    if (!unlocked) {
      const fromTier = tiers.find((t) => t.id === tier.unlockFrom);
      const fromPts = skGetTierPts(cls, tier.unlockFrom);
      const pct = Math.min(100, Math.round((fromPts / tier.unlock) * 100));
      lockHTML = `<div class="sk-lock">
        <span style="opacity:.5;font-size:1rem">🔒</span>
        <div style="flex:1">
          <span>Butuh <strong style="color:var(--gold)">${tier.unlock} pts</strong> di ${tier.unlockLabel} — ${fromPts}/${tier.unlock}</span>
          <div class="sk-lock-bar"><div class="sk-lock-fill" style="width:${pct}%;background:${fromTier.color}"></div></div>
        </div>
      </div>`;
    }

    div.innerHTML = `
      <div class="sk-tier-hd">
        <div class="sk-tier-title">
          <span class="sk-badge" style="background:${tier.bg};color:${tier.color};border:1px solid ${tier.border};padding:2px 7px">${tier.badge}</span>
          ${tier.label}
        </div>
        <div class="sk-pts">Points: <b id="skpts-${tier.id}">${tierPts}</b></div>
      </div>
      ${lockHTML}
      <div class="sk-grid" id="skgrid-${tier.id}"></div>`;
    tc.appendChild(div);

    const grid = div.querySelector(`#skgrid-${tier.id}`);
    tier.skills.forEach((skill) => {
      const lv = skPts[skill.id] || 0;
      const pct = skill.max > 0 ? Math.round((lv / skill.max) * 100) : 0;
      const card = document.createElement("div");
      card.className =
        "sk-card" +
        (skill.prio ? " prio" : "") +
        (!unlocked ? " sk-locked" : "");
      card.innerHTML = `
        <div class="sk-ctop">
          <div class="sk-ico" style="background:${tier.bg};color:${tier.color};border:1px solid ${tier.border}">${skill.abbr}</div>
          <span class="sk-nm">${skill.name}</span>
          ${skill.prio ? '<span class="sk-star">Priority</span>' : ""}
        </div>
        <div class="sk-dsc">${skill.desc}</div>
        <div class="sk-ctrl">
          <button class="sk-btn" onclick="skAdj('${skill.id}','${tier.id}','${cls}',-1)">−</button>
          <div class="sk-bbar"><div class="sk-bfill" style="width:${pct}%;background:${tier.color}"></div></div>
          <span class="sk-lv">${lv}/${skill.max}</span>
          <button class="sk-btn" onclick="skAdj('${skill.id}','${tier.id}','${cls}',1)">+</button>
        </div>`;
      grid.appendChild(card);
    });
  });
}

function skAdj(sid, tid, cls, delta) {
  const tier = SK_DATA[cls]?.find((t) => t.id === tid);
  if (!tier || !skIsTierUnlocked(cls, tier)) return;
  const skill = tier.skills.find((s) => s.id === sid);
  const next = (skPts[sid] || 0) + delta;
  if (next < 0 || next > skill.max) return;
  skPts[sid] = next;
  skRenderTree(cls);
}

function skApplyRec() {
  const tiers = SK_DATA[_skClass];
  if (!tiers) return;
  function doTier(i) {
    if (i >= tiers.length) {
      skRenderTree(_skClass);
      return;
    }
    tiers[i].skills.forEach((s) => {
      skPts[s.id] = s.rec;
    });
    skRenderTree(_skClass);
    setTimeout(() => doTier(i + 1), 60);
  }
  doTier(0);
}
function skReset() {
  const tiers = SK_DATA[_skClass];
  if (!tiers) return;
  tiers.forEach((t) =>
    t.skills.forEach((s) => {
      skPts[s.id] = 0;
    }),
  );
  skRenderTree(_skClass);
}

const obs = new IntersectionObserver(
  (entries) => {
    entries.forEach((e) => {
      if (e.isIntersecting) {
        e.target.style.opacity = "1";
        e.target.style.transform = "translateY(0)";
      }
    });
  },
  { threshold: 0.08 },
);
document.querySelectorAll(".pc,.cc,.gc,.ab-card,.tpc,.fi").forEach((el, i) => {
  el.style.opacity = "0";
  el.style.transform = "translateY(22px)";
  el.style.transition = `opacity .5s ${i * 0.04}s ease, transform .5s ${i * 0.04}s ease, border-color .2s, background .4s`;
  obs.observe(el);
});
