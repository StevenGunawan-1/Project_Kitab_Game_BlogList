function openArticle(id) {
  const art = ARTICLES[id];
  if (!art) return;

  // Populate overlay
  document.getElementById("art-hero-img").style.backgroundImage =
    `url('${art.img}')`;
  document.getElementById("art-breadcat").textContent = art.cat.toUpperCase();
  document.getElementById("art-cat").textContent = art.cat;
  document.getElementById("art-title").textContent = art.title;
  document.getElementById("art-date").textContent = art.date;
  document.getElementById("art-read").textContent = art.read;
  document.getElementById("art-content").innerHTML = art.content;

  // Tags
  document.getElementById("art-tags").innerHTML = art.tags
    .map((t) => `<span class="art-tag">${t}</span>`)
    .join("");

  // Related posts
  const rg = document.getElementById("related-grid");
  rg.innerHTML = art.related
    .map((rid) => {
      const r = ARTICLES[rid];
      if (!r) return "";
      return `<div class="rel-card" onclick="openArticle('${rid}')">
      <img src="${r.img}" alt="${r.title}">
      <h4>${r.title}</h4>
    </div>`;
    })
    .join("");

  // Open overlay
  const overlay = document.getElementById("article-overlay");
  overlay.classList.add("open");
  overlay.scrollTop = 0;
  document.body.style.overflow = "hidden";
}

function closeArticle() {
  document.getElementById("article-overlay").classList.remove("open");
  document.body.style.overflow = "";
}

function shareArticle() {
  const title = document.getElementById("art-title").textContent;
  if (navigator.clipboard) {
    navigator.clipboard.writeText(window.location.href + " — " + title);
    showToast("🔗 Link artikel disalin!");
  } else {
    showToast("🔗 Salin URL dari browser kamu!");
  }
}

